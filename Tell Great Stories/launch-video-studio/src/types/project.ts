/**
 * Phase metadata for display in the stepper
 */
export interface PhaseInfo {
  id: ProjectStatus;
  name: string;
  description: string;
  order: number;
}

/**
 * All phases in order
 */
export const PHASES: PhaseInfo[] = [
  { id: 'discover', name: 'Discover', description: 'Extract the emotional story', order: 1 },
  { id: 'style', name: 'Style', description: 'Define visual direction', order: 2 },
  { id: 'storyboard', name: 'Storyboard', description: 'Plan scenes and shots', order: 3 },
  { id: 'images', name: 'Images', description: 'Generate keyframes', order: 4 },
  { id: 'videos', name: 'Videos', description: 'Animate scenes', order: 5 },
  { id: 'stitch', name: 'Stitch', description: 'Assemble timeline', order: 6 },
  { id: 'audio', name: 'Audio', description: 'Add voice and music', order: 7 },
  { id: 'complete', name: 'Complete', description: 'Export final video', order: 8 },
];

/**
 * Get phase info by status
 */
export function getPhaseInfo(status: ProjectStatus): PhaseInfo {
  const phase = PHASES.find(p => p.id === status);
  if (!phase) {
    throw new Error(`Unknown phase status: ${status}`);
  }
  return phase;
}

/**
 * Get the next phase after the current one
 */
export function getNextPhase(current: ProjectStatus): ProjectStatus | null {
  const currentPhase = getPhaseInfo(current);
  const nextPhase = PHASES.find(p => p.order === currentPhase.order + 1);
  return nextPhase?.id ?? null;
}

/**
 * Check if a phase is complete (has passed)
 */
export function isPhaseComplete(current: ProjectStatus, target: ProjectStatus): boolean {
  const currentPhase = getPhaseInfo(current);
  const targetPhase = getPhaseInfo(target);
  return currentPhase.order > targetPhase.order;
}

