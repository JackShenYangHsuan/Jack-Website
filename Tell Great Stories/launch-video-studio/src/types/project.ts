/**
 * Check if a storyboard is complete enough to proceed
 */
export function isStoryboardComplete(storyboard: Storyboard | null): boolean {
  if (!storyboard) return false;
  if (storyboard.scenes.length === 0) return false;

  // Check that total duration is close to target
  const totalDuration = storyboard.scenes.reduce((sum, s) => sum + s.duration, 0);
  const minDuration = storyboard.targetDuration * 0.8;
  const maxDuration = storyboard.targetDuration * 1.2;

  return totalDuration >= minDuration && totalDuration <= maxDuration;
}

